"""Shared modelling code: time blocks, training windows, features and models.

Notebook 03 (fit and tune) and notebook 04 (evaluate over time) both import
from this module, so the two notebooks always use the same definitions.

Study design ("expanding window"): the calls are cut into four time blocks.
A model is trained at three successive dates, each time on every call known
at that date, and is then tested on every later block.

Origin: generated by Claude (Anthropic), a generative AI assistant, at the
student's request. See "Declaration of tools" in README.md.
"""

from sklearn.compose import ColumnTransformer
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler

from src.data_utils import MACRO_COLUMNS

# Fixed seed, so that every run gives the same numbers.
SEED = 42

TARGET = "y"

# ---------------------------------------------------------------------------
# Time blocks, as (first month, last month) in "YYYY-MM" format, inclusive.
# There are no calls in Jan-Feb 2009 and Jan-Feb 2010.
# ---------------------------------------------------------------------------
BLOCKS = {
    "2008": ("2008-05", "2008-12"),
    "2009a": ("2009-03", "2009-05"),
    "2009b": ("2009-06", "2009-12"),
    "2010": ("2010-03", "2010-11"),
}

# Three training windows. Each one is trained on every call up to `fit_end`.
# Its settings are chosen by fitting on calls up to `tune_fit_end` and scoring
# on the months from `tune_valid` (the most recent part of the window).
# It is then tested on the blocks listed in `test_blocks`.
WINDOWS = {
    "A_end2008": {"fit_end": "2008-12",
                  "tune_fit_end": "2008-08", "tune_valid": ("2008-10", "2008-12"),
                  "test_blocks": ["2009a", "2009b", "2010"]},
    "B_may2009": {"fit_end": "2009-05",
                  "tune_fit_end": "2008-12", "tune_valid": ("2009-03", "2009-05"),
                  "test_blocks": ["2009b", "2010"]},
    "C_end2009": {"fit_end": "2009-12",
                  "tune_fit_end": "2009-05", "tune_valid": ("2009-06", "2009-12"),
                  "test_blocks": ["2010"]},
}

# ---------------------------------------------------------------------------
# Features
# ---------------------------------------------------------------------------
# Client and call characteristics, known before the call.
CLIENT_CATEGORICAL = ["job", "marital", "education", "default", "housing",
                      "loan", "contact", "day_of_week"]
CLIENT_NUMERIC = ["age", "campaign"]

# Contact history from earlier campaigns. Empty in mid-2008, but it fills up
# from late 2008, so the later windows can learn from it.
HISTORY_CATEGORICAL = ["poutcome"]
HISTORY_NUMERIC = ["previous"]

# Columns left out of every model, with the reason (see notebook 03).
#   duration: known only after the call (already removed in notebook 01).
#   month: each window contains only some months; later blocks contain
#       months the model has never seen, so the month mostly encodes the
#       period rather than a seasonal effect.
#   pdays: coded 999 for "never contacted", which would distort a numeric
#       scale; its information is carried by poutcome and previous.
EXCLUDED = ["duration", "month", "pdays"]

# Two feature sets: the main one, and one without the economic context
# (robustness check).
FEATURE_SETS = {
    "with_macro": {"categorical": CLIENT_CATEGORICAL + HISTORY_CATEGORICAL,
                   "numeric": CLIENT_NUMERIC + HISTORY_NUMERIC + MACRO_COLUMNS},
    "without_macro": {"categorical": CLIENT_CATEGORICAL + HISTORY_CATEGORICAL,
                      "numeric": CLIENT_NUMERIC + HISTORY_NUMERIC},
}

MODEL_NAMES = ["logistic_regression", "random_forest"]

# Candidate settings, chosen on the tuning months of each window.
GRIDS = {
    "logistic_regression": [{"C": c} for c in [0.01, 0.1, 1]],
    "random_forest": [{"max_depth": d, "min_samples_leaf": leaf}
                      for d in [6, 12, None] for leaf in [10, 50]],
}


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def add_block(df, blocks=BLOCKS):
    """Add a 'block' column (2008, 2009a, 2009b, 2010)."""
    df = df.copy()
    df["block"] = None
    for name, (start, end) in blocks.items():
        inside = (df["year_month"] >= start) & (df["year_month"] <= end)
        df.loc[inside, "block"] = name
    if df["block"].isna().any():
        raise ValueError("Some calls fall outside every block")
    return df


def calls_up_to(df, last_month):
    """All calls made up to and including `last_month` ("YYYY-MM")."""
    return df[df["year_month"] <= last_month]


def calls_between(df, first_month, last_month):
    """All calls made between two months, both included."""
    return df[(df["year_month"] >= first_month) & (df["year_month"] <= last_month)]


def make_preprocessor(feature_set):
    """Turn categories into 0/1 columns and put numbers on a common scale.

    Categories never seen in training are encoded as all zeros instead of
    raising an error.
    """
    cols = FEATURE_SETS[feature_set]
    return ColumnTransformer([
        ("categories", OneHotEncoder(handle_unknown="ignore"), cols["categorical"]),
        ("numbers", StandardScaler(), cols["numeric"]),
    ])


def make_model(model_name, feature_set, **params):
    """Build an unfitted pipeline: preprocessing followed by the classifier."""
    if model_name == "logistic_regression":
        classifier = LogisticRegression(max_iter=2000, **params)
    elif model_name == "random_forest":
        classifier = RandomForestClassifier(n_estimators=300, random_state=SEED,
                                            n_jobs=-1, **params)
    else:
        raise ValueError(f"Unknown model: {model_name}")
    return Pipeline([("prepare", make_preprocessor(feature_set)),
                     ("model", classifier)])


def feature_columns(feature_set):
    """All input columns of a feature set, in the order the models use them."""
    cols = FEATURE_SETS[feature_set]
    return cols["categorical"] + cols["numeric"]


def target_vector(df):
    """The target as 1 (subscribed) or 0 (did not subscribe)."""
    return (df[TARGET] == "yes").astype(int)
